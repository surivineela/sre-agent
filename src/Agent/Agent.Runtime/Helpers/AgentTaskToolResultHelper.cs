    /// <summary>
    /// Finds and updates an existing AzCli tool execution result, or creates a new one if not found
    /// </summary>
    private async Task SaveOrUpdateAzCliToolResultAsync(Guid agentTaskId, InvestigationStepContext? stepContext, AzCliExecution execution, Guid threadId)
    {
        try
        {
            var agentTask = await _agentTaskRepository.GetAgentTaskAsync(threadId, agentTaskId);
            if (agentTask?.Properties is not IncidentInvestigationTaskProperties properties)
            {
                _logger.LogInternalWarning("Agent task {AgentTaskId} not found or has invalid properties", agentTaskId);
                return;
            }

            // Find existing tool execution by AzCli execution ID
            ToolExecutionResult? existingToolResult = null;
            
            if (stepContext == null)
            {
                // Search in initial investigation steps
                foreach (var step in properties.InitialInvestigation.GatheringContext.Steps)
                {
                    existingToolResult = step.ToolExecutions.FirstOrDefault(te => 
                        te.Type == ToolExecutionType.AzCli && 
                        te.AzCliExecution?.Id == execution.Id);
                    if (existingToolResult != null) break;
                }
            }
            else if (stepContext.StepPhase == "InitialInvestigation")
            {
                // Search in initial investigation steps
                foreach (var step in properties.InitialInvestigation.GatheringContext.Steps)
                {
                    existingToolResult = step.ToolExecutions.FirstOrDefault(te => 
                        te.Type == ToolExecutionType.AzCli && 
                        te.AzCliExecution?.Id == execution.Id);
                    if (existingToolResult != null) break;
                }
            }
            else if (stepContext.StepPhase == "HypothesisValidation")
            {
                // Search in hypothesis steps
                var hypothesis = GetHypothesisById(properties, stepContext.HypothesisId);
                if (hypothesis != null)
                {
                    foreach (var step in hypothesis.Steps)
                    {
                        existingToolResult = step.ToolExecutions.FirstOrDefault(te => 
                            te.Type == ToolExecutionType.AzCli && 
                            te.AzCliExecution?.Id == execution.Id);
                        if (existingToolResult != null) break;
                    }
                }
            }

            if (existingToolResult != null)
            {
                // Update existing tool execution
                existingToolResult.AzCliExecution = execution;
                existingToolResult.ExecutedTimestamp = DateTime.UtcNow;
                _logger.LogInternalInformation("Updated existing AzCli tool execution {ToolExecutionId} with status {Status}", 
                    existingToolResult.Id, execution.Status);
            }
            else
            {
                // Create new tool execution
                var newToolResult = new ToolExecutionResult
                {
                    Type = ToolExecutionType.AzCli,
                    KustoQueryResults = string.Empty, // Frontend uses AzCliExecution object directly
                    ExecutedTimestamp = DateTime.UtcNow,
                    AzCliExecution = execution
                };

                // Add to appropriate step based on context
                if (stepContext == null)
                {
                    var initStep = GetOrCreateDefaultInitialInvestigationStep(properties, defaultInitialInvestigationToolResultsStepTitle);
                    initStep.ToolExecutions.Add(newToolResult);
                }
                else if (stepContext.StepPhase == "InitialInvestigation")
                {
                    var initStep = GetOrCreateDefaultInitialInvestigationStep(properties, defaultInitialInvestigationToolResultsStepTitle);
                    initStep.ToolExecutions.Add(newToolResult);
                }
                else if (stepContext.StepPhase == "HypothesisValidation")
                {
                    var hypothesis = GetHypothesisById(properties, stepContext.HypothesisId);
                    if (hypothesis != null)
                    {
                        var hypStep = GetOrCreateDefaultHypothesisStep(hypothesis, stepContext.StepName);
                        hypStep.ToolExecutions.Add(newToolResult);
                    }
                }

                _logger.LogInternalInformation("Created new AzCli tool execution {ToolExecutionId} with status {Status}", 
                    newToolResult.Id, execution.Status);
            }
            
            await _agentTaskRepository.UpdateAgentTaskAsync(agentTask);
        }
        catch (Exception ex)
        {
            _logger.LogInternalError(ex, "Failed to save or update AzCli tool result for agent task {AgentTaskId}", agentTaskId);
        }
    }

    /// <summary>
    /// Handles pending AzCli execution for agent tasks
    /// </summary>
    public async Task HandlePendingAzCliAsync(Guid threadId, AzCliExecution execution, Guid agentTaskId, InvestigationStepContext? stepContext)
    {
        await SaveOrUpdateAzCliToolResultAsync(agentTaskId, stepContext, execution, threadId);
        await SendAgentTaskUpdateWithAzCliStatusAsync(threadId, execution, agentTaskId);
        
        _logger.LogInternalInformation("AzCli {Status} - stored in agent task and sent approval request stream", execution.Status);
    }

    /// <summary>
    /// Handles running AzCli execution for agent tasks
    /// </summary>
    public async Task HandleRunningAzCliAsync(Guid threadId, AzCliExecution execution, Guid agentTaskId, InvestigationStepContext? stepContext)
    {
        await SaveOrUpdateAzCliToolResultAsync(agentTaskId, stepContext, execution, threadId);
        await SendAgentTaskUpdateWithAzCliStatusAsync(threadId, execution, agentTaskId);
        
        _logger.LogInternalInformation("AzCli Running - updated agent task and sent task update");
    }

    /// <summary>
    /// Handles completed AzCli execution for agent tasks
    /// </summary>
    public async Task HandleCompletedAzCliAsync(Guid threadId, AzCliExecution execution, Guid agentTaskId, InvestigationStepContext? stepContext)
    {
        await SaveOrUpdateAzCliToolResultAsync(agentTaskId, stepContext, execution, threadId);
        
        // Add reasoning message for agent context
        var azCliMessage = new ChatMessage(ChatRole.Tool, $"Command: {execution.Command}\nOutput: {execution.Output ?? execution.Error}");
        await AddToolResultToAgentChatHistoryAsync(threadId, azCliMessage);
        
        // Send task update to agent task panel
        await SendAgentTaskUpdateWithAzCliStatusAsync(threadId, execution, agentTaskId);
        
        _logger.LogInternalInformation("AzCli {Status} - stored in agent task and sent task update", execution.Status);
    }

    /// <summary>
    /// Sends agent task update with AzCli status
    /// </summary>
    private async Task SendAgentTaskUpdateWithAzCliStatusAsync(Guid threadId, AzCliExecution execution, Guid agentTaskId)
    {
        try
        {
            // Get the current agent task to send full update
            var agentTask = await _agentTaskRepository.GetAgentTaskAsync(threadId, agentTaskId);
            if (agentTask == null)
            {
                _logger.LogInternalWarning("Could not find agent task {AgentTaskId} for AzCli status update", agentTaskId);
                return;
            }

            // Set task status based on AzCli execution status
            var originalStatus = agentTask.Status;
            var newStatus = execution.Status switch
            {
                AzCliExecutionStatus.Pending or AzCliExecutionStatus.PendingAuthorization => AgentTaskStatus.PendingUserApproval,
                AzCliExecutionStatus.Running => AgentTaskStatus.InProgress,
                AzCliExecutionStatus.Completed => originalStatus, // Don't change overall task status for individual completions
                AzCliExecutionStatus.Failed => originalStatus,
                AzCliExecutionStatus.Cancelled => originalStatus,
                _ => originalStatus
            };
            
            _logger.LogInternalInformation("Agent task status mapping: AzCli {AzCliStatus} -> Agent Task {OriginalStatus} -> {NewStatus}", 
                execution.Status, originalStatus, newStatus);
            
            agentTask.Status = newStatus;

            // Save the updated agent task to the database
            await _agentTaskRepository.UpdateAgentTaskAsync(agentTask);

            // Use the standard task update mechanism (sends whole task)
            var taskJson = JsonSerializer.Serialize(agentTask, JsonSerializerOptions.Web);
            await _streamingService.StreamTaskUpdateAsync(threadId, taskJson);
            
            _logger.LogInternalInformation("Sent full agent task update for AzCli {Status} on task {AgentTaskId}", execution.Status, agentTaskId);
        }
        catch (Exception ex)
        {
            _logger.LogInternalError(ex, "Failed to send agent task update for AzCli {Status} on task {AgentTaskId}", execution.Status, agentTaskId);
        }
    }

    #endregion
}
